  async function checkForUpdate() {
    if (!navigator.onLine) return;
    // Fixes the update checker from showing up on every reload
    if (!navigator.serviceWorker || !navigator.serviceWorker.controller) return;
    try {
      // The plain fetch goes through the service worker cache-first handler
      const [localRes, remoteRes] = await Promise.all([
        fetch('./version.txt'),
        fetch(`./version.txt?t=${Date.now()}`, { cache: 'no-store' }),
      ]);
      if (!localRes.ok || !remoteRes.ok) return;
      const local = (await localRes.text()).trim();
      const remote = (await remoteRes.text()).trim();
      
      // Migrate old setting
      if (settings.skipUpdateCheck) {
        settings.skippedUpdateVersion = remote;
        delete settings.skipUpdateCheck;
        saveSettings();
        return;
      }
      
      if (settings.skippedUpdateVersion === remote) return;

      // Any mismatch triggers the popup - so if a downgrade is required, it will be shown
      if (local && remote && local !== remote) {
        showUpdatePopup(local, remote);
      }
    } catch {
      // Offline or fetch failed — silently skip
    }
  }

  function findHueForColor(hex) {
    const h = (hex || '').toLowerCase();
    for (const hue of HUE_NAMES) {
      if (COLOR_PALETTE[hue].includes(h)) return hue;
    }
    return 'Blue';
  }

  function shadeSwatchesHtml(hue, selected) {
    return COLOR_PALETTE[hue].map(c =>
      `<div class="color-swatch${c === selected ? ' selected' : ''}" data-color="${c}" style="background:${c}"></div>`
    ).join('');
  }

  function colorSwatchesHtml(selected, pickerId) {
    const hue = findHueForColor(selected);
    let html = `<select class="hue-select" id="hue-${pickerId}">`;
    for (const h of HUE_NAMES) {
      html += `<option value="${h}"${h === hue ? ' selected' : ''}>${h}</option>`;
    }
    html += `</select>`;
    html += `<div class="color-swatch-row" id="swatches-${pickerId}">${shadeSwatchesHtml(hue, selected)}</div>`;
    return html;
  }

  function iconPickerHtml(selected) {
    return ICON_NAMES.map(name =>
      `<button type="button" class="icon-pick${name === selected ? ' selected' : ''}" data-icon="${name}">${svgIcon(name)}</button>`
    ).join('');
  }

